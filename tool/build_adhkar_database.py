def count_label(n):
    if n == 1:
        return 'مَرَّةً وَاحِدَةً'
    if n == 2:
        return 'مَرَّتَيْنِ'
    if 3 <= n <= 10:
        return f'{n} مَرَّاتٍ'
    return f'{n} مَرَّةً'

def run():
    print("Loading existing assets/data/adhkar.json...")
    with open('assets/data/adhkar.json', 'r', encoding='utf-8') as f:
        existing_catalog = json.load(f)

    # Dictionary of categories: id -> {id, title, subtitle, items}
    categories_dict = {}

    # Initialize with existing categories (migrating wudu_food cleanly)
    for cat in existing_catalog.get('categories', []):
        cat_id = cat['id']
        if cat_id == 'wudu_food':
            # Migrate items into wudu_taharah and food_drink
            for it in cat.get('items', []):
                it['content'] = clean_text(it.get('content') or it.get('arabic', ''))
                it['fadl'] = clean_text(it.get('fadl', ''))
                it['source'] = clean_text(it.get('source', ''))
                it['count_description'] = clean_text(it.get('count_description', ''))
                it['explanation_of_hadith_vocabulary'] = clean_text(it.get('explanation_of_hadith_vocabulary', ''))
                target_key = 'wudu_taharah' if 'وضوء' in it.get('fadl', '') or 'وضوء' in it.get('content', '') else 'food_drink'
                if target_key not in categories_dict:
                    if target_key == 'wudu_taharah':
                        categories_dict[target_key] = {
                            'id': target_key,
                            'title': 'أذكار الطهارة والوضوء',
                            'subtitle': 'أذكار الوضوء والخلاء ولبس الثياب',
                            'items': []
                        }
                    else:
                        categories_dict[target_key] = {
                            'id': target_key,
                            'title': 'أذكار الطعام والشراب',
                            'subtitle': 'الآداب النبوية عند الأكل والشرب والضيافة',
                            'items': []
                        }
                categories_dict[target_key]['items'].append(it)
            continue

        title = clean_text(cat['title'])
        if cat_id == 'distress':
            title = 'أذكار الكرب والهم والحفظ'
        subtitle = clean_text(cat['subtitle'])
        items = []
        for it in cat.get('items', []):
            it['content'] = clean_text(it.get('content') or it.get('arabic', ''))
            it['fadl'] = clean_text(it.get('fadl', ''))
            it['source'] = clean_text(it.get('source', ''))
            it['count_description'] = clean_text(it.get('count_description', ''))
            it['explanation_of_hadith_vocabulary'] = clean_text(it.get('explanation_of_hadith_vocabulary', ''))
            items.append(it)
        categories_dict[cat_id] = {
            'id': cat_id,
            'title': title,
            'subtitle': subtitle,
            'items': items
        }

    print("Fetching Hisn al-Muslim from GitHub repository...")
    url = 'https://raw.githubusercontent.com/rn0x/Adhkar-json/main/adhkar.json'
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=15) as resp:
        hisn_data = json.loads(resp.read().decode('utf-8'))

    # Helper to check if text already exists in category
    def contains_item(cat_items, text):
        norm_target = strip_tashkeel(text)[:40]
        for existing in cat_items:
            norm_ex = strip_tashkeel(existing.get('content', ''))[:40]
            if norm_target and norm_target == norm_ex:
                return True
        return False

    added_items_count = 0
    new_categories_created = set()

    for chapter in hisn_data:
        raw_title = chapter.get('category', '').strip()
        items_array = chapter.get('array', [])
        if not items_array:
            continue

        # Look up mapped category
        mapping = CATEGORY_MAP.get(raw_title)
        if mapping:
            target_id, target_title, target_subtitle = mapping
        else:
            # Fallback to general duas
            target_id, target_title, target_subtitle = ('duas', 'أدعية مأثورة وجامعة', 'أدعية نبوية ومأثورات من السنة النبوية المطهرة')

        if target_id not in categories_dict:
            categories_dict[target_id] = {
                'id': target_id,
                'title': target_title,
                'subtitle': target_subtitle,
                'items': []
            }
            new_categories_created.add(target_title)

        cat_entry = categories_dict[target_id]

        for item_idx, raw_item in enumerate(items_array, 1):
            text = clean_text(raw_item.get('text', ''))
            if not text or len(text) < 5:
                continue

            # Skip exact duplicate
            if contains_item(cat_entry['items'], text):
                continue

            count = raw_item.get('count', 1)
            try:
                count_int = int(count) if count else 1
            except Exception:
                count_int = 1

            new_id = f"{target_id}_hisn_{len(cat_entry['items']) + 1}"
            newItem = {
                "id": new_id,
                "order": len(cat_entry['items']) + 1,
                "type": 1,
                "content": text,
                "target": count_int,
                "count_description": count_label(count_int),
                "fadl": f"من سنن النبي ﷺ في {raw_title}",
                "source": "حصن المسلم من أذكار الكتاب والسنة",
                "hadith_text": text,
                "explanation_of_hadith_vocabulary": "",
                "transliteration": "",
                "meaning": ""
            }
            cat_entry['items'].append(newItem)
            added_items_count += 1

    # Reorder categories logically
    preferred_order = [
        'morning',          # 1. أذكار الصباح
        'evening',          # 2. أذكار المساء
        'after_prayer',     # 3. أذكار بعد الصلاة المفروضة
        'prayer_sunan',     # 4. سنن وأدعية الصلاة (استفتاح، ركوع، سجود، وتر، استخارة)
        'waking',           # 5. أذكار الاستيقاظ
        'sleeping',         # 6. أذكار النوم
        'mosque_adhan',     # 7. أذكار المسجد والأذان
        'home',             # 8. أذكار المنزل
        'wudu_taharah',     # 9. أذكار الطهارة والوضوء
        'food_drink',       # 10. أذكار الطعام والشراب والضيافة
        'travel',           # 11. أذكار السفر وركوب الدابة
        'distress',         # 12. أذكار الكرب ودفع الهم
        'sickness_funerals',# 13. أدعية المرض والجنائز والمصائب
        'nature_weather',   # 14. أذكار المطر والرعد والريح والظواهر
        'social_manners',   # 15. أذكار المجالس والآداب والمعاملات
        'fasting_hajj',     # 16. أذكار الصيام والحج والعمرة
        'tasbeeh',          # 17. التسبيح والتحميد
        'istighfar',        # 18. الاستغفار والتوبة
        'duas'              # 19. جوامع الدعاء والمأثورات
    ]

    final_categories = []
    for cat_id in preferred_order:
        if cat_id in categories_dict:
            final_categories.append(categories_dict[cat_id])

    # Append any remaining categories
    for cat_id, cat_data in categories_dict.items():
        if cat_id not in preferred_order:
            final_categories.append(cat_data)

    output = {'categories': final_categories}
    total_items = sum(len(c['items']) for c in final_categories)
    print(f"Generated {len(final_categories)} categories with {total_items} total authentic items (+{added_items_count} added)!")

    with open('assets/data/adhkar.json', 'w', encoding='utf-8') as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    stat = os.stat('assets/data/adhkar.json')
    print(f"Written to assets/data/adhkar.json ({stat.st_size // 1024} KB)")

if __name__ == '__main__':
    run()
