def clean_text(s):
    if not s:
        return ""
    s = re.sub(r'[\u200e\u200f\u202a-\u202e\u200b\ufeff]', '', s)
    s = s.replace('\r\n', '\n').strip()
    # Normalize multiple dots to clean punctuation
    s = re.sub(r'\.{2,}', '', s)
    return s.strip()

def strip_tashkeel(s):
    return re.sub(r'[\u064B-\u065F\u0670\u0640]', '', s)

