def extract_companion(text):
    clean = strip_tashkeel(text)
    for key, name in COMPANIONS_MAP:
        if re.search(r'(?:عن|سمع|سمعت|أن|قالت|قال)\s+' + key, clean):
            return name
    return 'أحد الصحابة الكرام رضي الله عنهم'

