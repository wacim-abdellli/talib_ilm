    with open('tool/classical_gems_curated.json', 'r', encoding='utf-8') as cf:
        classical_gems = json.load(cf)

    print(f"Ingesting {len(classical_gems)} curated gems from classical heritage...")
    existing_texts = set(g['text'].strip() for g in gems)
    added_count = 0

    for cg in classical_gems:
        txt = cg['text'].strip()
        if txt not in existing_texts:
            gems.append(cg)
            existing_texts.add(txt)
            added_count += 1

    print(f"Successfully added {added_count} distinct classical gems.")

    # 4. Strict Re-indexing and ID Normalization
    for idx, g in enumerate(gems, 1):
        g['id'] = f"gem_{idx:04d}"
        if not g.get('sourceRef'):
            g['sourceRef'] = 'حلية الأولياء / سير أعلام النبلاء'
        if not g.get('topic'):
            g['topic'] = g.get('category', 'درر السلف')

    print(f"Total gems now: {len(gems)}.")

    with open('assets/data/salaf_gems.json', 'w', encoding='utf-8') as out_f:
        json.dump({'gems': gems}, out_f, ensure_ascii=False, indent=2)

    print("assets/data/salaf_gems.json successfully updated.")

