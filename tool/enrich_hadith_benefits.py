def clean_arabic(text):
    if not text:
        return ""
    text = re.sub(r'[\u064B-\u065F\u0670\u0640]', '', text)
    text = re.sub(r'[إأآا]', 'ا', text)
    text = text.replace('ى', 'ي').replace('ة', 'ه')
    return text.lower()

