import 'dart:math' as math;

class VerifiedCity {
  final String id;
  final String name;
  final String? province;
  final String country;
  final String countryCode;
  final double latitude;
  final double longitude;
  final String calculationMethod;

  const VerifiedCity({
    required this.id,
    required this.name,
    this.province,
    required this.country,
    required this.countryCode,
    required this.latitude,
    required this.longitude,
    this.calculationMethod = 'mwl',
  });

  /// Computes approximate distance in kilometers (Haversine formula)
  double distanceTo(double lat, double lon) {
    const p = math.pi / 180.0;
    final a = 0.5 -
        math.cos((lat - latitude) * p) / 2 +
        math.cos(latitude * p) *
            math.cos(lat * p) *
            (1 - math.cos((lon - longitude) * p)) /
            2;
    return 12742 * math.asin(math.sqrt(a));
  }
}

class VerifiedCitiesCatalog {
  /// Finds nearest verified city within [maxDistanceKm] (default 35km)
  static VerifiedCity? findNearest(double lat, double lon, {double maxDistanceKm = 35.0}) {
    VerifiedCity? best;
    double bestDist = maxDistanceKm;

    for (final city in all) {
      final dist = city.distanceTo(lat, lon);
      if (dist < bestDist) {
        bestDist = dist;
        best = city;
      }
    }
    return best;
  }

  static final RegExp _tashkeelRegex = RegExp(r'[\u064B-\u065F\u0670]');
  static final RegExp _alefRegex = RegExp(r'[إأآا]');

  static final Map<String, String> _citySearchIndex = {
    for (final c in all)
      c.id: _normalize('${c.name} ${c.province ?? ''} ${c.country}'),
  };

  /// Search cities by normalized Arabic name or province
  static List<VerifiedCity> search(String query, {String? countryCode}) {
    final q = _normalize(query.trim());
    return all.where((c) {
      if (countryCode != null && countryCode.isNotEmpty && countryCode != 'ALL') {
        if (c.countryCode.toUpperCase() != countryCode.toUpperCase()) return false;
      }
      if (q.isEmpty) return true;
      final idx = _citySearchIndex[c.id];
      if (idx != null) {
        return idx.contains(q);
      }
      return _normalize(c.name).contains(q) ||
          (c.province != null && _normalize(c.province!).contains(q)) ||
          _normalize(c.country).contains(q);
    }).toList();
  }

  static String _normalize(String input) {
    return input
        .replaceAll(_tashkeelRegex, '') // remove tashkeel
        .replaceAll(_alefRegex, 'ا')
        .replaceAll('ة', 'ه')
        .replaceAll('ى', 'ي')
        .toLowerCase();
  }

