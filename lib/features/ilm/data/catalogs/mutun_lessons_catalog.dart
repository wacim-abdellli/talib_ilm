  /// Get verified lesson playlist for any book in the mutun curriculum
  static List<Lesson> getLessonsForBook(String bookId, {String? scholar, String? fallbackPlaylist}) {
    final list = _lessonsByBook[bookId];
    if (list != null && list.isNotEmpty) {
      if (scholar != null && scholar.isNotEmpty) {
        final filtered = list.where((l) => l.scholar == scholar).toList();
        if (filtered.isNotEmpty) return filtered;
      }
      return list;
    }
    // Fallback if dynamic custom book
    return Lesson.generateFromPlaylist(
      fallbackPlaylist ?? 'PLClZ7RmnwNVPdQHQ1NhNFgpiEeVSY7PYq',
      count: 5,
    );
  }

  /// Get all distinct scholars explaining this book
  static List<String> getScholarsForBook(String bookId) {
    final list = _lessonsByBook[bookId];
    if (list == null || list.isEmpty) return const [];
    final seen = <String>{};
    final scholars = <String>[];
    for (final l in list) {
      final s = l.scholar;
      if (s != null && s.isNotEmpty && seen.add(s)) {
        scholars.add(s);
      }
    }
    return scholars;
  }

  /// Get playlist ID for specific scholar and book
  static String? getPlaylistForScholar(String bookId, String scholar) {
    return _playlistsByScholar['$bookId::$scholar'];
  }

  /// Check if a book has a curated lecture series
  static bool hasLessons(String bookId) {
    return _lessonsByBook.containsKey(bookId);
  }
